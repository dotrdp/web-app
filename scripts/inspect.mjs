import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { existsSync, readFileSync } from 'node:fs';
await mkdir('/tmp/agrocebada-preview', { recursive: true });
const existingBrowser = '/home/rd/.cache/ms-playwright/chromium-1228/chrome-linux64/chrome';
const browser = await chromium.launch({ headless: true, executablePath: existsSync(existingBrowser) ? existingBrowser : undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:8080');
await page.getByRole('button', { name: 'Usar cuenta de prueba' }).click();
await page.screenshot({ path: '/tmp/agrocebada-preview/login.png' });
await page.getByRole('button', { name: 'Entrar a AgroCebada' }).click();
await page.getByTestId('map').waitFor();
await page.waitForTimeout(1800);
await page.screenshot({ path: '/tmp/agrocebada-preview/dashboard.png', fullPage: true });
await page.getByRole('tab', { name: 'NDVI · Landsat C2' }).click();
await page.waitForFunction(() => Number(document.querySelector('[data-testid="map"]')?.getAttribute('data-valid-pixels')) > 0);
await page.screenshot({ path: '/tmp/agrocebada-preview/ndvi.png', fullPage: true });
const health = await (await page.request.get('http://127.0.0.1:8080/api/health')).json();
const html = await (await page.request.get('http://127.0.0.1:8080/')).text();
const pidFile = new URL('../.data-cache/server/runtime.pid', import.meta.url);
const pid = existsSync(pidFile) ? Number(readFileSync(pidFile, 'utf8')) : null;
if (pid) process.kill(pid, 0);
console.log(JSON.stringify({ title: await page.title(), errors, production: !html.includes('/src/main.tsx'), health, liveServerPid: pid, parcels: await page.getByTestId('map').getAttribute('data-parcel-count'), validNdviPixels: await page.getByTestId('map').getAttribute('data-valid-pixels'), displayedNdviPixels: await page.getByTestId('map').getAttribute('data-displayed-pixels') }));
await browser.close();
